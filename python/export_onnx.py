"""Export the released Maia-2 checkpoints to ONNX (fp32, int8, fp16-storage).

Usage (from the repo root):
    .venv/bin/python python/export_onnx.py [rapid] [blitz]

Outputs:
    models/maia2-<type>.onnx        fp32, dynamic batch axis
    models/maia2-<type>.int8.onnx   dynamic int8 quantization (MatMul/Gemm, per-channel weights)
    models/maia2-<type>.fp16.onnx   fp16 *storage* of the float weights, cast back to fp32
                                    at session load (compute stays fp32)
    src/vocab.ts                    move vocabulary (index -> UCI) generated from maia2
"""

import json
import os
import sys
from pathlib import Path

import numpy as np
import onnx
import torch
from maia2 import model as maia_model
from maia2.utils import create_elo_dict, get_all_possible_moves
from onnx import TensorProto, helper, numpy_helper
from onnxruntime.quantization import QuantType, quantize_dynamic

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "models"
WEIGHTS = ROOT / "maia2_models"
OPSET = 17


def fp16_storage(src: Path, dst: Path, min_elems: int = 1024):
    """Store float initializers as fp16 + a Cast node back to fp32.

    onnxruntime constant-folds the Casts when the session is created, so inference
    runs in fp32 with weights rounded to fp16: half the file, near-identical outputs.
    """
    m = onnx.load(str(src))
    g = m.graph
    new_inits, casts = [], []
    for init in g.initializer:
        if init.data_type == TensorProto.FLOAT and np.prod(init.dims) >= min_elems:
            h = numpy_helper.from_array(numpy_helper.to_array(init).astype(np.float16), init.name + "__fp16")
            new_inits.append(h)
            casts.append(helper.make_node("Cast", [h.name], [init.name], to=TensorProto.FLOAT, name=init.name + "__cast"))
        else:
            new_inits.append(init)
    del g.initializer[:]
    g.initializer.extend(new_inits)
    nodes = list(g.node)
    del g.node[:]
    g.node.extend(casts + nodes)
    onnx.checker.check_model(m)
    onnx.save(m, str(dst))


class Maia2Export(torch.nn.Module):
    """Keep only what inference needs: the move logits and the raw value output.

    Side-info head (fc_2) is dropped: it is an auxiliary training target and
    maia2's own inference helpers ignore it.
    """

    def __init__(self, inner):
        super().__init__()
        self.inner = inner

    def forward(self, boards, elo_self, elo_oppo):
        logits_maia, _, logits_value = self.inner(boards, elo_self, elo_oppo)
        return logits_maia, logits_value


def write_vocab():
    moves = get_all_possible_moves()
    elo_dict = create_elo_dict()
    out = ROOT / "src" / "vocab.ts"
    body = (
        "// GENERATED by python/export_onnx.py from maia2.utils.get_all_possible_moves().\n"
        "// Index i of the model's move logits corresponds to ALL_MOVES[i], expressed in the\n"
        "// side-to-move-is-White frame (Black positions are mirrored before encoding).\n"
        "// Do not edit by hand.\n\n"
        f"export const ALL_MOVES: readonly string[] = {json.dumps(moves)};\n\n"
        f"export const NUM_MOVES = {len(moves)};\n\n"
        f"export const NUM_ELO_CATEGORIES = {len(elo_dict)};\n"
    )
    out.write_text(body)
    print(f"wrote {out} ({len(moves)} moves, {len(elo_dict)} elo categories)")


def export(kind: str):
    MODELS.mkdir(exist_ok=True)
    m = maia_model.from_pretrained(kind, "cpu", save_root=str(WEIGHTS))
    m.eval()
    wrapper = Maia2Export(m).eval()

    boards = torch.zeros((2, 18, 8, 8), dtype=torch.float32)
    elo_self = torch.tensor([5, 5], dtype=torch.long)
    elo_oppo = torch.tensor([5, 5], dtype=torch.long)

    fp32_path = MODELS / f"maia2-{kind}.onnx"
    torch.onnx.export(
        wrapper,
        (boards, elo_self, elo_oppo),
        str(fp32_path),
        input_names=["boards", "elo_self", "elo_oppo"],
        output_names=["logits_move", "logits_value"],
        dynamic_axes={
            "boards": {0: "batch"},
            "elo_self": {0: "batch"},
            "elo_oppo": {0: "batch"},
            "logits_move": {0: "batch"},
            "logits_value": {0: "batch"},
        },
        opset_version=OPSET,
        do_constant_folding=True,
        dynamo=False,
    )
    onnx.checker.check_model(onnx.load(str(fp32_path)))

    int8_path = MODELS / f"maia2-{kind}.int8.onnx"
    quantize_dynamic(
        str(fp32_path),
        str(int8_path),
        weight_type=QuantType.QInt8,
        op_types_to_quantize=["MatMul", "Gemm"],
        per_channel=True,
    )

    fp16_path = MODELS / f"maia2-{kind}.fp16.onnx"
    fp16_storage(fp32_path, fp16_path)

    for p in (fp32_path, int8_path, fp16_path):
        print(f"{p.name}: {os.path.getsize(p):,} bytes")


if __name__ == "__main__":
    kinds = sys.argv[1:] or ["rapid"]
    write_vocab()
    for k in kinds:
        export(k)
